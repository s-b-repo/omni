//! The cross-process contracts, and the version gate every one of them passes
//! through.
//!
//! # The rule
//!
//! omni joins five systems that were written separately, so the seams between
//! them are **versioned messages, never shared memory**. That is the same
//! discipline unifur and subnext already state about their own channel:
//!
//! > An unknown (or missing) version is a loud error that names it, never a
//! > silent reinterpretation.
//!
//! [`check_version`] is the single implementation of that rule in this crate,
//! and the `contract` certificate group proves two things about it: an unknown
//! version is rejected, and a **missing** version is rejected *identically* —
//! because `#[serde(default)]` turns an absent field into `0`, and `0` is
//! simply an unknown version. A peer that silently drops a field and a peer
//! that speaks a newer dialect must not look the same to the receiver.
//!
//! # What omni reuses and what it adds
//!
//! The context message shapes ([`ContextQuery`], [`ContextHit`],
//! [`Provenance`], [`ContextPut`], [`MemoryAppend`]) are **already deployed at
//! version 1 on both sides** of `/srv/m-sda/unifur/interop/`, pinned in
//! `contract.json`, and guarded by a cross-repo drift test on the subnext side.
//! omni implements that contract; it does not redefine it. Forking the struct
//! would create a second shape that is correct today and silently incompatible
//! after the next bump.
//!
//! [`VERSIONED_MESSAGES`] is the enumeration of everything in that list, and it
//! is what `omni-verify`'s `GATED` table is checked against — the table is a
//! claim about coverage, this is the thing being covered.
//!
//! [`HookPacket`] is omni's own message — the failure-evidence envelope the
//! harness-edit loop reads. It is version 1, in omni's own channel directory.

use serde::{Deserialize, Serialize};
use serde_json::Value;

use crate::error::Error;

// ── Versions ────────────────────────────────────────────────────────────────
//
// Each constant mirrors the deployed value on the other side. Changing one is a
// protocol change: the peer must be able to name the same number, which is
// exactly what `omni contract` prints and what the certificate checks.

/// `ContextQuery` schema version. Mirrors unifur's `CONTEXT_QUERY_VERSION` and
/// subnext's `CONTEXT_QUERY_VERSION`.
pub const CONTEXT_QUERY_VERSION: u32 = 1;

/// `ContextHit` schema version. Mirrors unifur's `CONTEXT_HIT_VERSION`.
pub const CONTEXT_HIT_VERSION: u32 = 1;

/// `ChannelRequest` / `ChannelResponse` envelope version.
pub const CHANNEL_ENVELOPE_VERSION: u32 = 1;

/// `ContextPut` schema version. Mirrors unifur's `CONTEXT_PUT_VERSION`.
/// Accepted on read; omni does not currently submit puts, but it must be able to
/// recognise one if a peer sends it.
pub const CONTEXT_PUT_VERSION: u32 = 1;

/// `MemoryAppend` schema version. Mirrors unifur's `MEMORY_APPEND_VERSION`.
/// Same caveat as [`CONTEXT_PUT_VERSION`].
pub const MEMORY_APPEND_VERSION: u32 = 1;

/// `HookPacket` schema version — omni's own envelope.
pub const HOOK_PACKET_VERSION: u32 = 1;

/// Every versioned message this crate defines, as `(name, version)`.
///
/// Deliberately *not* the same list as `omni-verify`'s `GATED` table. This one
/// is what omni-core **declares**; that one is what the version gate is
/// **claimed to cover**. Collapsing them would make the comparison between them
/// trivially true, and the whole point of rule 5 is that adding a message here
/// and forgetting the table there is a finding rather than a silent gap — so a
/// certificate holds the two together, and this list is its other half.
///
/// `ChannelRequest` and `ChannelResponse` share
/// [`CHANNEL_ENVELOPE_VERSION`]: one envelope, two directions, and the gate is
/// stated once for both.
pub const VERSIONED_MESSAGES: &[(&str, u32)] = &[
    ("ContextQuery", CONTEXT_QUERY_VERSION),
    ("ContextHit", CONTEXT_HIT_VERSION),
    ("ContextPut", CONTEXT_PUT_VERSION),
    ("MemoryAppend", MEMORY_APPEND_VERSION),
    ("ChannelRequest", CHANNEL_ENVELOPE_VERSION),
    ("ChannelResponse", CHANNEL_ENVELOPE_VERSION),
    ("HookPacket", HOOK_PACKET_VERSION),
];

/// The directory the deployed unifur↔subnext channel lives in.
///
/// omni reads it; it does not assume it exists, and never creates it as a side
/// effect of constructing a path.
pub const INTEROP_DIR: &str = "/srv/m-sda/unifur/interop";

/// The machine-readable contract document inside [`INTEROP_DIR`].
///
/// Generated by the side that owns the contract from the same constants its
/// code enforces, so it cannot drift from the implementation. omni parses it at
/// startup to confirm the deployed versions are the ones it was built against,
/// and reports a mismatch rather than proceeding.
pub const CONTRACT_FILE: &str = "contract.json";

/// Suffix of a submitted request file in the channel directory.
pub const REQUEST_SUFFIX: &str = ".request.json";

/// Suffix of a responder's answer file in the channel directory.
pub const RESPONSE_SUFFIX: &str = ".response.json";

/// Protocol name both sides record in `contract.json`.
pub const PROTOCOL: &str = "unifur-subnext-interop";

/// Reject a message whose `version` this build does not speak.
///
/// `supported` is passed rather than looked up so the same function gates every
/// message type and there is no per-type table to forget to update.
pub fn check_version(kind: &'static str, got: u32, supported: u32) -> Result<(), Error> {
    if got != supported {
        return Err(Error::ContractVersion { kind, got, supported });
    }
    Ok(())
}

// ── Context messages (deployed contract, version 1) ─────────────────────────

/// A retrieval request, as unifur's client side writes it.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct ContextQuery {
    /// Schema version; current is [`CONTEXT_QUERY_VERSION`]. Missing parses as
    /// `0` and is rejected exactly like any other unknown version.
    #[serde(default)]
    pub version: u32,
    /// The text to retrieve for.
    pub text: String,
    /// How many hits the asker wants. `0` means "the responder's default".
    pub k: usize,
    /// unifur's taxonomy hint (`pentest`, `coding`, …).
    ///
    /// The deployed responder records this in its poll report and does **not**
    /// filter on it: DCR's documents carry a filesystem `source`, so it does
    /// not own that taxonomy, and an honest over-retrieval beats a filter that
    /// silently returns nothing. omni keeps the field for the same reason.
    #[serde(default)]
    pub field: String,
}

impl ContextQuery {
    /// Build a version-1 query. Constructing through a constructor rather than
    /// a struct literal means no call site can forget the version.
    pub fn new(text: &str, k: usize, field: &str) -> Self {
        Self {
            version: CONTEXT_QUERY_VERSION,
            text: text.to_string(),
            k,
            field: field.to_string(),
        }
    }

    /// Pass the version gate. The message has been deserialised; this is the
    /// check that turns an unknown number into a named error.
    pub fn validate(&self) -> Result<(), Error> {
        check_version("ContextQuery", self.version, CONTEXT_QUERY_VERSION)
    }
}

/// Where a retrieved piece of context came from.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct Provenance {
    pub source: String,
    pub path: String,
}

/// One scored retrieved document.
///
/// `text` is the **rendered ladder line** (`[node_id L2] …`), not the raw
/// document, and `score` is the planner's utility, not a similarity. Recording
/// that here is the difference between a consumer that knows what it is being
/// handed and one that assumes cosine scores and re-scores garbage.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct ContextHit {
    #[serde(default)]
    pub version: u32,
    pub id: String,
    pub score: f64,
    pub text: String,
    #[serde(default)]
    pub provenance: Provenance,
}

impl ContextHit {
    pub fn validate(&self) -> Result<(), Error> {
        check_version("ContextHit", self.version, CONTEXT_HIT_VERSION)
    }
}

/// A context document handed to the context runtime for storage.
///
/// The write half of the deployed contract: [`ContextQuery`] asks what the store
/// already holds, this is how something gets in there. omni builds its own
/// corpus through the indexer rather than by submitting puts, so this type
/// exists to *recognise* one a peer sends — the cheaper of the two obligations,
/// and a real one, because a message type that cannot be read is a shape this
/// build would reinterpret by accident.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct ContextPut {
    /// Schema version; current is [`CONTEXT_PUT_VERSION`]. Missing parses as
    /// `0` and is rejected exactly like any other unknown version.
    #[serde(default)]
    pub version: u32,
    /// The document's stable id, assigned by whoever submitted it.
    #[serde(default)]
    pub id: String,
    /// What kind of context this is (`"document"`, `"memory"`, …).
    ///
    /// Recorded by the receiving store, not interpreted by it — the taxonomy is
    /// the submitter's, exactly as [`ContextQuery::field`] is. An honest
    /// over-retrieval beats a filter that quietly returns nothing.
    #[serde(default)]
    pub kind: String,
    /// The full document text.
    #[serde(default)]
    pub text: String,
    /// Free-form provenance hints and tags; `null` when there are none.
    ///
    /// An opaque [`Value`] rather than a struct, because the deployed contract
    /// leaves this shape to the submitter and a typed map of strings could not
    /// express what it does: `null` (nothing offered) and `{}` (an offer of
    /// nothing) are different documents and stay different here.
    #[serde(default)]
    pub meta: Value,
}

impl ContextPut {
    /// Build a version-1 put. Constructing through a constructor rather than a
    /// struct literal means no call site can forget the version.
    pub fn new(id: &str, kind: &str, text: &str, meta: Value) -> Self {
        Self {
            version: CONTEXT_PUT_VERSION,
            id: id.to_string(),
            kind: kind.to_string(),
            text: text.to_string(),
            meta,
        }
    }

    /// Pass the version gate. The message has been deserialised; this is the
    /// check that turns an unknown number into a named error.
    pub fn validate(&self) -> Result<(), Error> {
        check_version("ContextPut", self.version, CONTEXT_PUT_VERSION)
    }
}

/// One write into the context runtime's Merkle-chained long-term memory: past
/// chats and runs become retrievable context, and nothing here is ever a weight
/// edit.
///
/// The payload is an opaque [`Value`] because its shape is owned by the memory
/// log, not by the model that produced the conversation. omni's obligation is
/// to carry it and to refuse a version it does not speak; inventing a schema
/// for it would be the fork `docs/CONTRACT.md` warns against, one level down.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct MemoryAppend {
    /// Schema version; current is [`MEMORY_APPEND_VERSION`]. Missing parses as
    /// `0` and is rejected exactly like any other unknown version.
    #[serde(default)]
    pub version: u32,
    /// What to append. Owned by the receiving memory log.
    #[serde(default)]
    pub payload: Value,
}

impl MemoryAppend {
    /// Build a version-1 append.
    pub fn new(payload: Value) -> Self {
        Self { version: MEMORY_APPEND_VERSION, payload }
    }

    /// Pass the version gate. The message has been deserialised; this is the
    /// check that turns an unknown number into a named error.
    pub fn validate(&self) -> Result<(), Error> {
        check_version("MemoryAppend", self.version, MEMORY_APPEND_VERSION)
    }
}

// ── omni's own message ──────────────────────────────────────────────────────

/// A batch of failure evidence for the harness-edit loop.
///
/// This is the omni counterpart of Harness-R1's "failure trace packet": a
/// bounded, sanitised set of episodes that failed, plus the *deterministic*
/// runtime signals derived from them. Deliberately no model-authored failure
/// labels — if a debugger model had graded the failures, the reward would be
/// measuring the grader.
///
/// [`signals`] is sorted by key so two runs over the same episodes produce
/// byte-identical packets, which is what makes the reward cache safe to key on
/// the packet's own hash.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct HookPacket {
    #[serde(default)]
    pub version: u32,
    /// Which profile the episodes were run under (`pentest`, …).
    pub profile: String,
    /// One-line description of what recurred.
    pub summary: String,
    /// Per-episode evidence, already truncated and redacted.
    pub episodes: Vec<HookEpisode>,
    /// Deterministic counts derived from the episodes, not from prose.
    #[serde(default)]
    pub signals: Vec<(String, u64)>,
}

/// One failing episode, as evidence.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct HookEpisode {
    /// Stable task identity. The reward's baseline/patched pairing is keyed on
    /// this, never on a positional index — matching integers is not proof of a
    /// matched comparison.
    pub task_id: String,
    /// The outcome measure (pass rate, shaped reward, …).
    pub score: f64,
    /// How the episode ended.
    pub status: String,
    /// Turn count.
    pub turns: usize,
    /// The redacted transcript.
    pub transcript: String,
}

impl HookPacket {
    /// Build a version-1 packet. Signals are sorted and de-duplicated here, at
    /// construction, so the invariant cannot be forgotten downstream.
    pub fn new(profile: &str, summary: &str, episodes: Vec<HookEpisode>) -> Self {
        let mut signals = signals_from(&episodes);
        signals.sort();
        signals.dedup();
        Self {
            version: HOOK_PACKET_VERSION,
            profile: profile.to_string(),
            summary: summary.to_string(),
            episodes,
            signals,
        }
    }

    pub fn validate(&self) -> Result<(), Error> {
        check_version("HookPacket", self.version, HOOK_PACKET_VERSION)
    }

    /// Total turns across the packet's episodes.
    ///
    /// An empty packet totals zero rather than being an error: a hook that edits
    /// nothing is a legitimate outcome, and the caller decides what an empty
    /// evidence set means.
    pub fn total_turns(&self) -> u64 {
        self.episodes.iter().map(|e| e.turns as u64).sum()
    }
}

/// Derive deterministic runtime signals from episodes.
///
/// Counting, not interpretation. Every field here is a function of the episode
/// list, so two builds that agree on the episodes agree on the signals — which
/// is the property the reward cache depends on.
fn signals_from(episodes: &[HookEpisode]) -> Vec<(String, u64)> {
    let mut signals: Vec<(String, u64)> = Vec::new();
    let total: u64 = episodes.len() as u64;
    signals.push(("episodes".to_string(), total));
    signals.push(("total_turns".to_string(), episodes.iter().map(|e| e.turns as u64).sum()));
    signals.push((
        "zero_turn_episodes".to_string(),
        episodes.iter().filter(|e| e.turns == 0).count() as u64,
    ));

    // Terminal statuses, counted by exact string so an unrecognised status is
    // simply not counted rather than being folded into a catch-all.
    for status in ["task_limit_reached", "budget_exhausted", "policy_blocked", "tool_error"] {
        let n = episodes.iter().filter(|e| e.status == status).count() as u64;
        if n > 0 {
            signals.push((format!("status:{status}"), n));
        }
    }
    signals
}

// ── Id hygiene ──────────────────────────────────────────────────────────────

/// Characters permitted in a channel request id.
///
/// An id becomes a filename in a shared directory, so this is a path-traversal
/// gate, not a naming convention. The set is exactly what the deployed
/// responder accepts; narrowing it on one side only would make the two halves
/// disagree about what a legal id is.
pub fn validate_id(id: &str) -> Result<(), Error> {
    if id.is_empty() {
        return Err(Error::Format("channel id must not be empty".into()));
    }
    if id == "." || id == ".." {
        return Err(Error::Format(format!("channel id {id:?} is a directory reference")));
    }
    if !id
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
    {
        return Err(Error::Format(format!(
            "channel id {id:?} contains a character outside [A-Za-z0-9-_]; \
             only those are allowed because the id becomes a file name in the \
             channel directory"
        )));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Assert that `r` is an error carrying a `ContractVersion` with the
    /// expected numbers, without panicking on the success path.
    ///
    /// The success path returns `Err` rather than `panic!` because the crate
    /// denies both: `clippy::panic` with `allow-panic-in-tests = false`, and
    /// `Result::expect_err`. Tests here return `Result` and use `?` instead.
    fn assert_version_err(r: Result<(), Error>, kind: &'static str, got: u32, supported: u32) -> Result<(), Error> {
        let Err(err) = r else {
            return Err(Error::Format(format!(
                "{kind} version {got} validated against supported {supported}"
            )));
        };
        match err {
            Error::ContractVersion { kind: k, got: g, supported: s } => {
                assert_eq!(k, kind, "error names the wrong message kind");
                assert_eq!(g, got, "error names the wrong got version");
                assert_eq!(s, supported, "error names the wrong supported version");
                Ok(())
            }
            other => Err(Error::Format(format!("expected a version error, got {other}"))),
        }
    }

    #[test]
    fn a_version_1_query_validates() -> Result<(), Error> {
        ContextQuery::new("what is the server ip?", 6, "pentest").validate()
    }

    #[test]
    fn a_query_with_no_version_is_rejected_like_an_unknown_one() -> Result<(), Error> {
        // `#[serde(default)]` turns an absent `version` into 0, so the
        // "missing field" path and the "unknown version" path are the same
        // path. A peer that drops a field must not look different to us from a
        // peer speaking a newer dialect.
        let query = ContextQuery { version: 0, ..ContextQuery::default() };
        assert_version_err(query.validate(), "ContextQuery", 0, CONTEXT_QUERY_VERSION)
    }

    #[test]
    fn a_future_version_names_both_numbers() -> Result<(), Error> {
        let err = check_version("HookPacket", 2, 1).err().ok_or_else(|| {
            Error::Format("a future version must not validate".into())
        })?;
        let msg = err.to_string();
        assert!(msg.contains('2'), "message must name the got version: {msg}");
        assert!(msg.contains('1'), "message must name the supported version: {msg}");
        Ok(())
    }

    #[test]
    fn ids_reject_traversal_and_separators() {
        for bad in ["", ".", "..", "../evil", "a/b", "a\\b", "a b", "a;b"] {
            assert!(
                validate_id(bad).is_err(),
                "{bad:?} must be rejected: it becomes a file name"
            );
        }
    }

    #[test]
    fn ids_accept_what_the_deployed_responder_accepts() -> Result<(), Error> {
        for good in ["r1", "A_b-9", "ctx-3336511-1791718557487399007-0"] {
            validate_id(good)?;
        }
        Ok(())
    }

    #[test]
    fn packet_signals_are_sorted_and_reproducible() -> Result<(), Error> {
        let episodes = vec![
            HookEpisode { task_id: "t1".into(), status: "task_limit_reached".into(), turns: 12, ..Default::default() },
            HookEpisode { task_id: "t2".into(), status: "ok".into(), turns: 3, ..Default::default() },
        ];
        let a = HookPacket::new("pentest", "recurring loop", episodes.clone());
        let b = HookPacket::new("pentest", "recurring loop", episodes);
        assert_eq!(a, b, "the same episodes must produce the same packet");
        let mut sorted = a.signals.clone();
        sorted.sort();
        assert_eq!(a.signals, sorted, "signals must be sorted at construction");
        assert_eq!(a.total_turns(), 15);
        Ok(())
    }

    #[test]
    fn a_packet_with_no_version_is_rejected() -> Result<(), Error> {
        let packet = HookPacket { version: 0, ..HookPacket::default() };
        assert_version_err(packet.validate(), "HookPacket", 0, HOOK_PACKET_VERSION)
    }

    /// The deployed `ContextPut` shape, as a peer would write it.
    const PUT_JSON: &str =
        r#"{"version":1,"id":"doc-1","kind":"document","text":"a corpus document","meta":{"corpus":"cybercorpus"}}"#;

    /// The deployed `MemoryAppend` shape.
    const APPEND_JSON: &str = r#"{"version":1,"payload":{"kind":"chat","turns":42}}"#;

    #[test]
    fn a_put_from_the_deployed_shape_validates_and_round_trips() -> Result<(), Error> {
        let put: ContextPut = serde_json::from_str(PUT_JSON)?;
        put.validate()?;
        assert_eq!(put.id, "doc-1");
        assert_eq!(put.kind, "document");
        assert_eq!(put.text, "a corpus document");
        // The meta object survives as itself: an opaque payload that arrived as
        // an object must not come back as a string or vanish into `null`.
        assert_eq!(put.meta["corpus"], serde_json::Value::from("cybercorpus"));
        assert_eq!(put, ContextPut::new("doc-1", "document", "a corpus document", put.meta.clone()));
        Ok(())
    }

    #[test]
    fn an_append_from_the_deployed_shape_validates_and_round_trips() -> Result<(), Error> {
        let append: MemoryAppend = serde_json::from_str(APPEND_JSON)?;
        append.validate()?;
        assert_eq!(append.payload["turns"], serde_json::Value::from(42));
        assert_eq!(append, MemoryAppend::new(append.payload.clone()));
        Ok(())
    }

    #[test]
    fn a_put_with_no_version_is_rejected_like_an_unknown_one() -> Result<(), Error> {
        let omitted: ContextPut = serde_json::from_str(r#"{"id":"doc-1","kind":"document","text":"t","meta":null}"#)?;
        assert_version_err(omitted.validate(), "ContextPut", 0, CONTEXT_PUT_VERSION)?;
        let explicit = ContextPut { version: 0, ..ContextPut::default() };
        assert_version_err(explicit.validate(), "ContextPut", 0, CONTEXT_PUT_VERSION)
    }

    #[test]
    fn an_append_with_no_version_is_rejected_like_an_unknown_one() -> Result<(), Error> {
        let omitted: MemoryAppend = serde_json::from_str(r#"{"payload":{"kind":"chat"}}"#)?;
        assert_version_err(omitted.validate(), "MemoryAppend", 0, MEMORY_APPEND_VERSION)?;
        let explicit = MemoryAppend { version: 0, ..MemoryAppend::default() };
        assert_version_err(explicit.validate(), "MemoryAppend", 0, MEMORY_APPEND_VERSION)
    }

    #[test]
    fn a_hit_with_no_version_is_rejected_like_an_unknown_one() -> Result<(), Error> {
        let hit: ContextHit = serde_json::from_str(r#"{"id":"goal_1","score":1.5,"text":"t","provenance":{"source":"s","path":"p"}}"#)?;
        assert_version_err(hit.validate(), "ContextHit", 0, CONTEXT_HIT_VERSION)?;
        let explicit = ContextHit { version: 0, ..ContextHit::default() };
        assert_version_err(explicit.validate(), "ContextHit", 0, CONTEXT_HIT_VERSION)
    }

    #[test]
    fn the_declared_versioned_messages_are_distinct_and_at_one() -> Result<(), Error> {
        // The enumeration `omni-verify` checks its `GATED` table against. Two
        // entries with the same name would make that comparison pass twice
        // while covering one message, and an empty list would make it pass
        // vacuously, so both are checked here rather than trusted to review.
        assert!(
            !VERSIONED_MESSAGES.is_empty(),
            "an empty enumeration describes nothing and would satisfy every comparison"
        );
        for (i, (name, version)) in VERSIONED_MESSAGES.iter().enumerate() {
            assert_eq!(*version, 1, "{name} is not at the deployed version 1");
            for (later_name, _) in &VERSIONED_MESSAGES[i + 1..] {
                assert!(name != later_name, "{name} is declared twice");
            }
        }
        Ok(())
    }
}